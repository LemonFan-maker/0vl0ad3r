fun getThemePalette(type: OvlThemeType, darkTheme: Boolean = false): ThemePalette {
    return when (type) {
        OvlThemeType.Sakura -> SakuraPalette
        OvlThemeType.Beige -> BeigePalette
        OvlThemeType.Slate -> SlatePalette
        OvlThemeType.Cyber -> CyberPalette
        OvlThemeType.Matcha -> MatchaPalette
        OvlThemeType.Nord -> NordPalette
    }
}

fun getTerminalThemePalette(
    type: TerminalThemeType,
    customBgHex: String = "#1E1E2E",
    customFgHex: String = "#CDD6F4"
): TerminalThemePalette {
    return when (type) {
        TerminalThemeType.Parchment -> TerminalParchment
        TerminalThemeType.Matrix -> TerminalMatrix
        TerminalThemeType.Solarized -> TerminalSolarized
        TerminalThemeType.Monokai -> TerminalMonokai
        TerminalThemeType.Custom -> createCustomTerminalPalette(customBgHex, customFgHex)
    }
}

fun TerminalThemePalette.colorForAnsi(code: Int): Color {
    return when (code) {
        30 -> ansiBlack
        31 -> ansiRed
        32 -> ansiGreen
        33 -> ansiYellow
        34 -> ansiBlue
        35 -> ansiMagenta
        36 -> ansiCyan
        37 -> ansiWhite
        90 -> ansiBrightBlack
        91 -> ansiBrightRed
        92 -> ansiBrightGreen
        93 -> ansiBrightYellow
        94 -> ansiBrightBlue
        95 -> ansiBrightMagenta
        96 -> ansiBrightCyan
        97 -> ansiBrightWhite
        else -> foreground
    }
}
