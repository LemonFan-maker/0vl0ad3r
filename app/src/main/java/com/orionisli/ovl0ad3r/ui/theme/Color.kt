fun createCustomTerminalPalette(customBgHex: String, customFgHex: String): TerminalThemePalette {
    val bg = runCatching { Color(android.graphics.Color.parseColor(customBgHex.trim())) }
        .getOrDefault(Color(0xFF1E1E2E))
    val fg = runCatching { Color(android.graphics.Color.parseColor(customFgHex.trim())) }
        .getOrDefault(Color(0xFFCDD6F4))
    val border = Color(fg.red, fg.green, fg.blue, alpha = 0.35f)
    return TerminalThemePalette(
        name = "Custom",
        background = bg,
        foreground = fg,
        border = border,
        cursor = fg,
        selection = Color(fg.red, fg.green, fg.blue, alpha = 0.20f),
        ansiBlack = bg,
        ansiRed = Color(0xFFEF4444),
        ansiGreen = Color(0xFF10B981),
        ansiYellow = Color(0xFFF59E0B),
        ansiBlue = Color(0xFF3B82F6),
        ansiMagenta = Color(0xFF8B5CF6),
        ansiCyan = Color(0xFF06B6D4),
        ansiWhite = fg,
        ansiBrightBlack = Color(0xFF64748B),
        ansiBrightRed = Color(0xFFF87171),
        ansiBrightGreen = Color(0xFF34D399),
        ansiBrightYellow = Color(0xFFFBBF24),
        ansiBrightBlue = Color(0xFF60A5FA),
        ansiBrightMagenta = Color(0xFFA78BFA),
        ansiBrightCyan = Color(0xFF22D3EE),
        ansiBrightWhite = Color(0xFFFFFFFF)
    )
}

